"""Regenerate homepage WebP assets from the original PNGs (requires Pillow)."""

import base64
from io import BytesIO
from pathlib import Path

from PIL import Image


root = Path(__file__).resolve().parents[1]
images = root / "public/assets/images"

for name in ("sabang-dolphins-hero", "sabang-footer-sunset", "sabang-journey-sunset"):
    with Image.open(images / f"{name}.png") as source:
        image = source.convert("RGB")
        image.save(images / f"{name}.webp", "WEBP", quality=82, method=6)
        if name == "sabang-journey-sunset":
            small = image.resize((640, round(image.height * 640 / image.width)), Image.Resampling.LANCZOS)
            small.save(images / f"{name}-640.webp", "WEBP", quality=82, method=6)
            preview = image.resize((32, round(image.height * 32 / image.width)), Image.Resampling.LANCZOS)
            buffer = BytesIO()
            preview.save(buffer, "WEBP", quality=50, method=6)
            data = base64.b64encode(buffer.getvalue()).decode("ascii")
            (root / "src/pages/home-image-preview.css").write_text(
                '/* Generated by scripts/optimize-home-images.py. */\n'
                '.sk-plan-visual { background-image: url("data:image/webp;base64,'
                + data + '"); background-size: cover; background-position: 45% center; }\n'
                '@media (max-width: 760px) { .sk-plan-visual { background-position: center 54%; } }\n',
                encoding="utf-8",
            )
        print(f"{name}: {source.size}, {Path(source.filename).stat().st_size:,} -> {(images / f'{name}.webp').stat().st_size:,} bytes")
